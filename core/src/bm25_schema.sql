CREATE TABLE IF NOT EXISTS docs(id TEXT PRIMARY KEY,length INTEGER NOT NULL,dataset TEXT,file TEXT,role TEXT);
CREATE INDEX IF NOT EXISTS docs_scope ON docs(dataset,file);
CREATE TABLE IF NOT EXISTS postings(term TEXT,doc TEXT REFERENCES docs(id) ON DELETE CASCADE,tf INTEGER NOT NULL,PRIMARY KEY(term,doc)) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS postings_doc ON postings(doc);
CREATE TABLE IF NOT EXISTS frequencies(term TEXT PRIMARY KEY,df INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS frequencies_df ON frequencies(df);
CREATE TABLE IF NOT EXISTS ancestors(ancestor TEXT,doc TEXT REFERENCES docs(id) ON DELETE CASCADE,PRIMARY KEY(ancestor,doc)) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS ancestors_doc ON ancestors(doc);
CREATE TABLE IF NOT EXISTS corpus(id INTEGER PRIMARY KEY CHECK(id=1),n INTEGER,length INTEGER,revision TEXT);
